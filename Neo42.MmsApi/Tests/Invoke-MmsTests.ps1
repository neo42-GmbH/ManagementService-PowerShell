#requires -version 5
<#
.SYNOPSIS
	Runs the test suite of Neo42.MmsApi.
.DESCRIPTION
	Entry point for all three test levels. The level decides what a run is
	allowed to touch:

		Unit         offline. No server, no configuration, runs anywhere.
		Integration  reads from the server named in the test configuration.
		Write        changes data, and only on a server declared as a lab.
		All          all three, in that order.

	Integration and Write need Tests\mms.tests.config.psd1. That file is written
	by hand, is never generated by this script, and is ignored by git. Without it
	the tests that need it report themselves as skipped instead of failing, so a
	plain 'Unit' run on a machine without an MMS stays green.

	The summary at the end lists the skipped tests explicitly. A skip is not the
	same as a pass: it says 'this could not be verified here', and for a suite
	whose main job is to spot the breaking changes of a new MMS version that
	distinction is the whole point.
.PARAMETER Scope
	Which level to run. Default 'Unit'.
.PARAMETER Path
	Restrict the run to one file or folder, for example a single .Tests.ps1 while
	writing it.
.PARAMETER Output
	Pester output verbosity. 'Detailed' lists every test, 'Normal' only the
	failures.
.PARAMETER ResultPath
	Writes an NUnit result file. Nothing is written by default: a result file can
	contain data read from the server, so it does not belong in the repository
	(Tests\TestResults\ is gitignored if you want one there).
.PARAMETER PassThru
	Returns the Pester result object instead of only setting the exit code.
.EXAMPLE
	.\Invoke-MmsTests.ps1
	The offline suite. This is what runs before a commit.
.EXAMPLE
	.\Invoke-MmsTests.ps1 -Scope Integration -Output Detailed
	Reads from the configured server and changes nothing.
.EXAMPLE
	.\Invoke-MmsTests.ps1 -Scope Write
	Only works with IsLab and Write.Enabled set in the test configuration.
.EXAMPLE
	.\Invoke-MmsTests.ps1 -Path .\Unit\Test-MmsShouldProcess.Tests.ps1 -Output Detailed
#>
[CmdletBinding()]
param (
	[Parameter(Position = 0)]
	[ValidateSet('Unit', 'Integration', 'Write', 'All')]
	[string]
	$Scope = 'Unit',

	[Parameter()]
	[string[]]
	$Path,

	[Parameter()]
	[ValidateSet('None', 'Normal', 'Detailed', 'Diagnostic')]
	[string]
	$Output = 'Normal',

	[Parameter()]
	[string]
	$ResultPath,

	[Parameter()]
	[switch]
	$PassThru
)

$ErrorActionPreference = 'Stop'

# Pester 6 is required for the assertion syntax, the tag filtering and the
# module scoped mocks this suite is built on. It runs on Windows PowerShell 5.1.
$pester = Get-Module -ListAvailable -Name 'Pester' |
	Where-Object { $_.Version -ge [version]'6.0.0' } |
	Sort-Object -Property Version -Descending |
	Select-Object -First 1

if ($null -eq $pester) {
	throw ("Pester 6 or newer is required, found: " +
		(((Get-Module -ListAvailable -Name 'Pester').Version | Sort-Object -Descending) -join ', ') +
		". Install it with: Install-Module Pester -Scope CurrentUser -Force -SkipPublisherCheck")
}

Import-Module -Name $pester.Path -Force -ErrorAction Stop

. (Join-Path -Path $PSScriptRoot -ChildPath 'TestHelpers\MmsTestContext.ps1')
$context = Get-MmsTestContext

$scopes = if ($Scope -eq 'All') { @('Unit', 'Integration', 'Write') } else { @($Scope) }

Write-Host ''
Write-Host ('Neo42.MmsApi tests  |  Pester {0}  |  PowerShell {1}' -f $pester.Version, $PSVersionTable.PSVersion) -ForegroundColor Cyan
Write-Host ('Scope        : {0}' -f ($scopes -join ', '))
Write-Host ('Module       : {0}' -f (Get-MmsTestModuleManifest))
Write-Host ('Configuration: {0}' -f $(if ($context.HasConfig) { $context.ConfigPath } else { "none ({0})" -f $context.ConfigPath }))
if ($context.HasConfig) {
	Write-Host ('Server       : {0}{1}' -f $context.ServerLabel, $(if ($context.IsLab) { '  [declared a lab]' } else { '' }))
}

# Refuse early and clearly rather than letting every single write test skip.
if ($scopes -contains 'Write' -and $null -ne $context.WriteSkip) {
	Write-Host ''
	Write-Warning ('Write tests cannot run: {0}' -f $context.WriteSkip)
	if ($Scope -eq 'Write') {
		exit 2
	}
	$scopes = @($scopes | Where-Object { $_ -ne 'Write' })
}
if ($scopes -contains 'Integration' -and $null -ne $context.IntegrationSkip) {
	Write-Host ''
	Write-Warning ('Integration tests cannot run: {0}' -f $context.IntegrationSkip)
	if ($Scope -eq 'Integration') {
		exit 2
	}
	$scopes = @($scopes | Where-Object { $_ -ne 'Integration' })
}

$runPath = if ($PSBoundParameters.ContainsKey('Path')) {
	@($Path | ForEach-Object { (Resolve-Path -LiteralPath $_).ProviderPath })
}
else {
	@($scopes | ForEach-Object { Join-Path -Path $PSScriptRoot -ChildPath $_ } | Where-Object { Test-Path -LiteralPath $_ })
}

if (0 -eq @($runPath).Count) {
	Write-Warning 'Nothing to run.'
	exit 2
}

$configuration = New-PesterConfiguration
$configuration.Run.Path = $runPath
$configuration.Run.PassThru = $true
$configuration.Output.Verbosity = $Output
$configuration.Should.ErrorAction = 'Continue'

# The folder already selects the level. The tag is the second lock, so a test
# that ends up in the wrong folder still cannot run in a scope it does not
# belong to.
if (-not $PSBoundParameters.ContainsKey('Path')) {
	$configuration.Filter.Tag = $scopes
}

if (-not [string]::IsNullOrWhiteSpace($ResultPath)) {
	$directory = Split-Path -Path $ResultPath -Parent
	if (-not [string]::IsNullOrWhiteSpace($directory) -and -not (Test-Path -LiteralPath $directory)) {
		New-Item -ItemType Directory -Path $directory -Force | Out-Null
	}
	$configuration.TestResult.Enabled = $true
	$configuration.TestResult.OutputPath = $ResultPath
	Write-Warning ('A result file can contain data read from the server. Keep {0} out of the repository.' -f $ResultPath)
}

Write-Host ''
$result = Invoke-Pester -Configuration $configuration

Write-Host ''
Write-Host '-- summary ------------------------------------------------------' -ForegroundColor Cyan
Write-Host ('passed {0}  failed {1}  skipped {2}  duration {3:n1}s' -f
	$result.PassedCount, $result.FailedCount, $result.SkippedCount, $result.Duration.TotalSeconds)

# A skipped test is an open question, not a success. List them, because 'green
# with 40 skips' means almost nothing was actually verified.
$skipped = @($result.Tests | Where-Object { $_.Result -eq 'Skipped' })
if ($skipped.Count -gt 0) {
	Write-Host ''
	Write-Host 'not verified in this run:' -ForegroundColor Yellow
	foreach ($test in $skipped) {
		$reason = $test.ErrorRecord.TargetObject.Message
		if ([string]::IsNullOrWhiteSpace($reason)) { $reason = 'skipped' }
		Write-Host ('  - {0}' -f $test.ExpandedPath)
		Write-Host ('      {0}' -f $reason) -ForegroundColor DarkGray
	}
}

if ($PassThru) {
	$result
}

# Not FailedCount: a file that fails during discovery reports zero failed tests
# and would otherwise look like a pass.
if ($result.Result -ne 'Passed') {
	Write-Host ''
	Write-Host ('overall result: {0}' -f $result.Result) -ForegroundColor Red
	exit 1
}

Write-Host ''
Write-Host 'overall result: Passed' -ForegroundColor Green
exit 0
